/**
 * JSON pool -> one idempotent INSERT.
 *
 * Migrations here are pasted into the Supabase SQL editor by hand, so the seed
 * has to be a single statement you can paste too — not 178 of them. The whole
 * array goes in as one jsonb literal and Postgres unrolls it.
 *
 * `on conflict (source) do nothing` is what makes topping up the pool trivial:
 * append to the JSON, regenerate, paste again, and only new rows land. Nothing
 * already served to a week is disturbed. Edits to an existing question are
 * silently ignored — update the database by hand if a question must change.
 *
 *   node scripts/build-trivia-seed.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';

const IN = 'supabase/seed/trivia_questions.json';
const OUT = 'supabase/seed/trivia_questions.sql';

const pool = JSON.parse(readFileSync(IN, 'utf8'));

for (const [i, q] of pool.entries()) {
  const where = `${IN}[${i}] (${q.source})`;
  if (!q.source || !q.section || !q.prompt) throw new Error(`missing field in ${where}`);
  if (!Array.isArray(q.options) || q.options.length < 2 || q.options.length > 6) throw new Error(`bad options in ${where}: length ${q.options.length} (expected 2–6)`);
  if (!Number.isInteger(q.correct_index) || q.correct_index < 0 || q.correct_index >= q.options.length) {
    throw new Error(`correct_index out of range in ${where}`);
  }
}

const seen = new Set();
for (const q of pool) {
  if (seen.has(q.source)) throw new Error(`duplicate source: ${q.source}`);
  seen.add(q.source);
}

// Strip `used` — the database derives it from week_id being null.
const rows = pool.map(({ source, section, prompt, options, correct_index }) => ({
  source, section, prompt, options, correct_index,
}));

// Enforce the $seed$ dollar-quote invariant: if any row's serialized content
// contains the literal substring, the dollar-quoted string will be truncated.
const serialized = JSON.stringify(rows);
if (serialized.includes('$seed$')) {
  const faultySource = rows.find(r => JSON.stringify(r).includes('$seed$'))?.source;
  throw new Error(`$seed$ tag found in ${faultySource}`);
}

// $seed$ dollar-quoting: the questions contain single quotes and Georgian
// typographic marks, and nothing in them can contain this tag.
const sql = `-- Generated by scripts/build-trivia-seed.mjs — do not edit by hand.
-- ${rows.length} questions from the four 2015 ზოგადი უნარები variants.
-- Paste into the Supabase SQL editor AFTER 20260830000100_trivia.sql.

insert into public.trivia_questions (source, section, prompt, options, correct_index)
select e->>'source', e->>'section', e->>'prompt', e->'options', (e->>'correct_index')::int
  from jsonb_array_elements($seed$${serialized}$seed$::jsonb) as e
on conflict (source) do nothing;
`;

writeFileSync(OUT, sql);
console.log(`wrote ${OUT} — ${rows.length} questions`);
